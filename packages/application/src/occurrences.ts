export type MeasurementInput =
  | {
      readonly kind: 'numeric';
      readonly key: string;
      readonly value: number;
      readonly unit: string;
    }
  | { readonly kind: 'qualitative'; readonly key: string; readonly label: string };

export interface CompleteOccurrenceInput {
  readonly occurrenceId: OccurrenceId;
  /** ISO-8601 UTC. Defaults to now; may be backdated. */
  readonly completedAt?: string | undefined;
  readonly notes?: string | undefined;
  readonly cost?: { readonly minor: number; readonly currency: string } | undefined;
  readonly checklistResults?: readonly { itemId: ChecklistItemId; done: boolean }[] | undefined;
  readonly deviationReason?: string | undefined;
  readonly measurements?: readonly MeasurementInput[] | undefined;
}

export interface CompleteOccurrenceResult {
  readonly occurrence: Occurrence;
  readonly completion: Completion;
  readonly measurements: readonly Measurement[];
  /** Follow-on occurrences generated by the schedule (e.g. next in a completion interval). */
  readonly nextOccurrences: readonly Occurrence[];
}

function toMeasurementValue(m: MeasurementInput): Result<MeasurementValue> {
  if (m.kind === 'qualitative') return ok({ kind: 'qualitative', label: m.label });
  const q = quantity(m.value, m.unit);
  return q.ok ? ok({ kind: 'numeric', quantity: q.value }) : q;
}

/** The details a person can supply about a piece of finished work. */
export type CompletionDetails = Omit<CompleteOccurrenceInput, 'occurrenceId'>;

/**
 * Validates what the person entered and builds the completion and its
 * measurements, without saving anything. Shared by completing and correcting.
 */
export function buildCompletion(
  deps: Deps,
  activity: Activity,
  occurrence: { readonly id: OccurrenceId; readonly dueOn: LocalDate },
  input: CompletionDetails,
  now: Instant,
): Result<{ completion: Completion; measurements: Measurement[] }> {
  const issues: ValidationIssue[] = [];

  let completedAt = now;
  if (input.completedAt !== undefined) {
    const parsed = parseInstant(input.completedAt);
    if (parsed.ok) completedAt = parsed.value;
    else issues.push({ path: 'completedAt', message: 'must be an ISO-8601 UTC timestamp' });
  }

  let cost;
  if (input.cost) {
    const m = money(input.cost.minor, input.cost.currency);
    if (m.ok) cost = m.value;
    else issues.push({ path: 'cost', message: m.error.message });
  }

  // Checklist results must refer to this activity's items.
  const itemIds = new Set<string>(activity.checklist.map((c) => c.id));
  for (const r of input.checklistResults ?? []) {
    if (!itemIds.has(r.itemId)) {
      issues.push({ path: 'checklistResults', message: `unknown checklist item ${r.itemId}` });
    }
  }

  // Required measurements must be supplied, in the unit the activity expects.
  const supplied = input.measurements ?? [];
  for (const req of activity.measurementRequirements) {
    const m = supplied.find((x) => x.key === req.key);
    if (!m && req.required) {
      issues.push({ path: 'measurements', message: `${req.key} is required` });
    } else if (m?.kind === 'numeric' && m.unit !== req.unit) {
      issues.push({ path: 'measurements', message: `${req.key} must be recorded in ${req.unit}` });
    }
  }
  if (issues.length > 0) return err(validationError(issues));

  const completion = createCompletion({
    id: deps.ids.next<'Completion'>(),
    ownerId: deps.ownerId,
    now,
    activityId: activity.id,
    occurrenceId: occurrence.id,
    completedAt,
    plannedFor: occurrence.dueOn,
    notes: input.notes,
    cost,
    checklistResults: input.checklistResults,
    deviationReason: input.deviationReason,
  });
  if (!completion.ok) return completion;

  const measurements: Measurement[] = [];
  for (const m of supplied) {
    const value = toMeasurementValue(m);
    if (!value.ok) return value;
    const created = createMeasurement({
      id: deps.ids.next<'Measurement'>(),
      ownerId: deps.ownerId,
      now,
      key: m.key,
      value: value.value,
      measuredAt: completedAt,
      assetId: activity.assetId,
      activityId: activity.id,
      completionId: completion.value.id,
    });
    if (!created.ok) return created;
    measurements.push(created.value);
  }
  return ok({ completion: completion.value, measurements });
}

/**
 * Completes an occurrence: records the completion and any measurements,
 * resolves the occurrence, and lets the schedule produce what comes next.
 * Works fully offline and is atomic.
 */
export async function completeOccurrence(
  deps: Deps,
  input: CompleteOccurrenceInput,
): Promise<Result<CompleteOccurrenceResult>> {
  return transact(deps, async (repos) => {
    const now = deps.clock.now();

    const occurrence = found(
      'Occurrence',
      input.occurrenceId,
      await repos.occurrences.getById(input.occurrenceId),
    );
    if (!occurrence.ok) return occurrence;
    const activity = found(
      'Activity',
      occurrence.value.activityId,
      await repos.activities.getById(occurrence.value.activityId),
    );
    if (!activity.ok) return activity;

    const built = buildCompletion(deps, activity.value, occurrence.value, input, now);
    if (!built.ok) return built;
    const { completion, measurements } = built.value;

    const resolved = transitionOccurrence(occurrence.value, 'completed', now);
    if (!resolved.ok) return resolved;

    await repos.occurrences.save(resolved.value);
    await repos.completions.add(completion);
    for (const m of measurements) await repos.measurements.add(m);
    await repos.audit.add(
      auditEvent(deps, 'completion', completion.id, 'created', activity.value.name),
    );

    const schedule = occurrence.value.scheduleId
      ? await repos.schedules.getById(occurrence.value.scheduleId)
      : null;
    const nextOccurrences = schedule
      ? await ensureOccurrences(deps, repos, activity.value, schedule, {
          lastResolvedOn: localDateOf(completion.completedAt, schedule.timeZone),
        })
      : [];

    return ok({
      occurrence: resolved.value,
      completion,
      measurements,
      nextOccurrences,
    });
  });
}

/** Skips an occurrence on purpose. A skip restarts a completion interval. */
export async function skipOccurrence(
  deps: Deps,
  input: { occurrenceId: OccurrenceId; reason?: string | undefined },
): Promise<Result<{ occurrence: Occurrence; nextOccurrences: readonly Occurrence[] }>> {
  return transact(deps, async (repos) => {
    const now = deps.clock.now();
    const loaded = found(
      'Occurrence',
      input.occurrenceId,
      await repos.occurrences.getById(input.occurrenceId),
    );
    if (!loaded.ok) return loaded;
    const activity = found(
      'Activity',
      loaded.value.activityId,
      await repos.activities.getById(loaded.value.activityId),
    );
    if (!activity.ok) return activity;

    const skipped = transitionOccurrence(loaded.value, 'skipped', now);
    if (!skipped.ok) return skipped;
    await repos.occurrences.save(skipped.value);
    await repos.audit.add(
      auditEvent(deps, 'occurrence', skipped.value.id, 'updated', input.reason ?? 'skipped'),
    );

    const schedule = loaded.value.scheduleId
      ? await repos.schedules.getById(loaded.value.scheduleId)
      : null;
    const nextOccurrences = schedule
      ? await ensureOccurrences(deps, repos, activity.value, schedule, {
          lastResolvedOn: localDateOf(now, schedule.timeZone),
        })
      : [];
    return ok({ occurrence: skipped.value, nextOccurrences });
  });
}

export async function snoozeOccurrence(
  deps: Deps,
  input: { occurrenceId: OccurrenceId; until: string },
): Promise<Result<Occurrence>> {
  return transact(deps, async (repos) => {
    const until = parseLocalDate(input.until);
    if (!until.ok)
      return err(validationError([{ path: 'until', message: 'must be a YYYY-MM-DD date' }]));
    const loaded = found(
      'Occurrence',
      input.occurrenceId,
      await repos.occurrences.getById(input.occurrenceId),
    );
    if (!loaded.ok) return loaded;

    const snoozed = transitionOccurrence(loaded.value, 'snoozed', deps.clock.now(), {
      snoozedUntil: until.value,
    });
    if (!snoozed.ok) return snoozed;
    await repos.occurrences.save(snoozed.value);
    return ok(snoozed.value);
  });
}

export async function rescheduleOccurrence(
  deps: Deps,
  input: { occurrenceId: OccurrenceId; to: string },
): Promise<Result<Occurrence>> {
  return transact(deps, async (repos) => {
    const to = parseLocalDate(input.to);
    if (!to.ok) return err(validationError([{ path: 'to', message: 'must be a YYYY-MM-DD date' }]));
    const loaded = found(
      'Occurrence',
      input.occurrenceId,
      await repos.occurrences.getById(input.occurrenceId),
    );
    if (!loaded.ok) return loaded;

    const clash = (
      await repos.occurrences.list({
        activityId: loaded.value.activityId,
        status: ['pending', 'snoozed'],
        dueFrom: to.value,
        dueTo: to.value,
      })
    ).some((o) => o.id !== loaded.value.id);
    if (clash) return err(invariantError(`Another occurrence is already due on ${to.value}`));

    const moved = rescheduleOccurrenceEntity(loaded.value, to.value, deps.clock.now());
    if (!moved.ok) return moved;
    await repos.occurrences.save(moved.value);
    return ok(moved.value);
  });
}

